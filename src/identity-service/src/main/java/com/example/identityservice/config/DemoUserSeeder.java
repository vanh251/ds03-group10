package com.example.identityservice.config;

import com.example.identityservice.entity.User;
import com.example.identityservice.entity.UserRole;
import com.example.identityservice.repository.UserRepository;
import lombok.extern.slf4j.Slf4j;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.boot.ApplicationArguments;
import org.springframework.boot.ApplicationRunner;
import org.springframework.boot.autoconfigure.condition.ConditionalOnProperty;
import org.springframework.jdbc.core.namedparam.NamedParameterJdbcOperations;
import org.springframework.security.crypto.password.PasswordEncoder;
import org.springframework.stereotype.Component;

import java.sql.Timestamp;
import java.time.Instant;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.UUID;

/**
 * Creates fake DRIVER and PASSENGER accounts at startup so the demo (Register -> Login -> Trip) works on an empty
 * identity_db. All accounts share the password from app.seed.password.
 * The ids are fixed: driver-service seeds the matching driver profiles (driver_id = user id) with the same values,
 * see docs/test-data/identity/README.md. Emails that already exist are left untouched, so restarts are safe.
 * Turn it off with SEED_DATA_ENABLED=false.
 */
@Slf4j
@Component
@ConditionalOnProperty(prefix = "app.seed", name = "enabled", havingValue = "true")
public class DemoUserSeeder implements ApplicationRunner {

    static final List<DemoUser> DEMO_USERS = List.of(
            new DemoUser(driverId(1), "Tran Van Binh", "driver01@ds03.test", UserRole.DRIVER),
            new DemoUser(driverId(2), "Le Hoang Nam", "driver02@ds03.test", UserRole.DRIVER),
            new DemoUser(driverId(3), "Pham Minh Tuan", "driver03@ds03.test", UserRole.DRIVER),
            new DemoUser(driverId(4), "Hoang Duc Anh", "driver04@ds03.test", UserRole.DRIVER),
            new DemoUser(driverId(5), "Vu Thi Lan", "driver05@ds03.test", UserRole.DRIVER),
            new DemoUser(driverId(6), "Do Quang Huy", "driver06@ds03.test", UserRole.DRIVER),
            new DemoUser(driverId(7), "Bui Van Long", "driver07@ds03.test", UserRole.DRIVER),
            new DemoUser(driverId(8), "Dang Thi Mai", "driver08@ds03.test", UserRole.DRIVER),
            new DemoUser(driverId(9), "Ngo Thanh Son", "driver09@ds03.test", UserRole.DRIVER),
            new DemoUser(driverId(10), "Duong Van Khoa", "driver10@ds03.test", UserRole.DRIVER),
            new DemoUser(passengerId(1), "Nguyen Thi Hoa", "passenger01@ds03.test", UserRole.PASSENGER),
            new DemoUser(passengerId(2), "Ly Minh Chau", "passenger02@ds03.test", UserRole.PASSENGER),
            new DemoUser(passengerId(3), "Phan Gia Bao", "passenger03@ds03.test", UserRole.PASSENGER)
    );

    // users.user_id is generated by JPA, which refuses a preset id, so the fixed ids are inserted with SQL.
    // ON CONFLICT DO NOTHING covers another instance seeding the same row at the same time.
    private static final String INSERT_USER = """
            INSERT INTO users (user_id, email, password_hash, full_name, role, version, created_at, updated_at)
            VALUES (:userId, :email, :passwordHash, :fullName, :role, 0, :now, :now)
            ON CONFLICT DO NOTHING
            """;

    private final UserRepository userRepository;
    private final NamedParameterJdbcOperations jdbc;
    private final PasswordEncoder passwordEncoder;
    private final String demoPassword;

    public DemoUserSeeder(UserRepository userRepository,
                          NamedParameterJdbcOperations jdbc,
                          PasswordEncoder passwordEncoder,
                          @Value("${app.seed.password}") String demoPassword) {
        this.userRepository = userRepository;
        this.jdbc = jdbc;
        this.passwordEncoder = passwordEncoder;
        this.demoPassword = demoPassword;
    }

    /** d0000000-0000-4000-8000-0000000000NN; driver-service uses the same ids for the driver profiles. */
    static UUID driverId(int number) {
        return UUID.fromString(String.format("d0000000-0000-4000-8000-%012d", number));
    }

    /** a0000000-0000-4000-8000-0000000000NN */
    static UUID passengerId(int number) {
        return UUID.fromString(String.format("a0000000-0000-4000-8000-%012d", number));
    }

    @Override
    public void run(ApplicationArguments args) {
        int created = 0;
        for (DemoUser demo : DEMO_USERS) {
            Optional<User> existing = userRepository.findByEmail(demo.email());
            if (existing.isPresent()) {
                if (!demo.id().equals(existing.get().getUserId())) {
                    // Seeded by an older version with random ids: the driver profiles in driver_db will not match
                    log.warn("Demo user {} has id {} instead of {}; recreate identity_db to get the fixed ids",
                            demo.email(), existing.get().getUserId(), demo.id());
                }
                continue;
            }
            Timestamp now = Timestamp.from(Instant.now());
            created += jdbc.update(INSERT_USER, Map.of(
                    "userId", demo.id(),
                    "email", demo.email(),
                    "passwordHash", passwordEncoder.encode(demoPassword),
                    "fullName", demo.fullName(),
                    "role", demo.role().name(),
                    "now", now));
        }
        log.info("Demo user seeding finished: created={}, alreadyPresent={}", created, DEMO_USERS.size() - created);
    }

    record DemoUser(UUID id, String fullName, String email, UserRole role) {
    }
}
